// Package docsgen renders docs/tools.md from the registry, so the reference can
// never disagree with the code (`make docs-check` fails when it would).
package docsgen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/google/jsonschema-go/jsonschema"

	"github.com/abm9111/tailkeeper/internal/registry"
)

// Markdown renders every tool in reg, grouped by CLI area.
func Markdown(reg *registry.Registry) string {
	all := reg.All()
	var b strings.Builder
	b.WriteString("# tailkeeper tools\n\n")
	b.WriteString("Generated by `tailkeeper docs` from the tool registry. Do not edit by hand.\n\n")
	noun := "tools"
	if len(all) == 1 {
		noun = "tool"
	}
	fmt.Fprintf(&b, "%d %s. Each is an MCP tool (name below) and a CLI command. MCP advertises alpha tools only with `--enable-alpha` (or `mcp.enableAlpha`); the CLI runs them without it. A tool may send only some of the API operations listed for it, depending on its arguments and on what it finds.\n\n", len(all), noun)
	b.WriteString("Parameters carry their MCP argument names. On the CLI each is a kebab-case flag (`staleDays` is `--stale-days`), and a tool's only required text parameter may be given as a plain argument instead.\n\n")
	b.WriteString("Unless the configuration sets `personalData` to `show`, personal data in results is masked: fields listed as masked whole keep their first character, plus the domain of an email address; in every other untrusted field, email addresses are masked the same way and public IP addresses are cut to their network, except in fields listed as never masked and in fields listed as having only their email addresses masked. The error messages of tool calls are masked like untrusted fields, without pseudonyms: an error echoes what the caller typed, and a pseudonym beside a guess would confirm it. With a privacy key, each masked identifier and email address in a result ends in its pseudonym ([p:…]), and filters take pseudonyms; while masking is on, filters that would confirm a guessed value are refused.\n")
	area := ""
	for _, t := range all {
		m := t.Meta
		if m.Area != area {
			area = m.Area
			fmt.Fprintf(&b, "\n## %s\n", area)
		}
		fmt.Fprintf(&b, "\n### `%s`\n\n%s\n\n", m.Name, m.Summary)
		fmt.Fprintf(&b, "- CLI: `tailkeeper %s %s`\n", m.Area, m.Verb)
		fmt.Fprintf(&b, "- Tier: %s; stage: %s\n", m.Tier, m.Stage)
		if m.Title != "" {
			fmt.Fprintf(&b, "- Title: %s\n", m.Title)
		}
		if m.Credential == registry.CredOptional {
			b.WriteString("- Credential: optional; the tool also runs without one, for the inputs it can answer locally\n")
		}
		if m.OpenWorld {
			b.WriteString("- Sends your input to Tailscale: yes\n")
		}
		if len(m.Scopes) > 0 {
			fmt.Fprintf(&b, "- OAuth scopes: %s\n", code(m.Scopes))
		}
		if len(m.OptionalScopes) > 0 {
			parts := make([]string, len(m.OptionalScopes))
			for i, o := range m.OptionalScopes {
				parts[i] = "`" + o.Scope + "` (" + o.Reason + ")"
			}
			fmt.Fprintf(&b, "- Optional OAuth scopes: %s\n", strings.Join(parts, ", "))
		}
		if len(m.Operations) > 0 {
			fmt.Fprintf(&b, "- API operations: %s\n", code(m.Operations))
		}
		if m.PlanGate != "" {
			fmt.Fprintf(&b, "- Tailscale plans: %s\n", m.PlanGate)
		}
		if m.Notes != "" {
			fmt.Fprintf(&b, "- Note: %s\n", m.Notes)
		}
		if len(t.UntrustedFields) > 0 {
			fmt.Fprintf(&b, "- Untrusted output fields: %s\n", code(t.UntrustedFields))
		}
		if len(t.PersonalFields) > 0 {
			fmt.Fprintf(&b, "- Masked whole unless `personalData` is `show`: %s\n", code(t.PersonalFields))
		}
		if len(t.EmailFields) > 0 {
			fmt.Fprintf(&b, "- Email addresses masked unless `personalData` is `show`, the rest kept (configuration): %s\n", code(t.EmailFields))
		}
		if len(t.PlainFields) > 0 {
			fmt.Fprintf(&b, "- Untrusted but never masked (configuration): %s\n", code(t.PlainFields))
		}
		params(&b, t.InputSchema)
	}
	coverageSection(&b, reg)
	return b.String()
}

func params(b *strings.Builder, s *jsonschema.Schema) {
	if s == nil || len(s.Properties) == 0 {
		b.WriteString("\nNo parameters.\n")
		return
	}
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("\n| Parameter | Type | Required | Description |\n|---|---|---|---|\n")
	for _, n := range names {
		p := s.Properties[n]
		req := ""
		if required[n] {
			req = "yes"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", n, typeOf(p), req, cell(p.Description))
	}
}

// cell makes text safe inside a Markdown table cell: backslashes first, so the
// pipe escapes that follow stay escapes, and line breaks become spaces.
var cell = strings.NewReplacer(`\`, `\\`, "|", `\|`, "\r\n", " ", "\n", " ", "\r", " ").Replace

func typeOf(p *jsonschema.Schema) string {
	t := p.Type
	if t == "" {
		for _, x := range p.Types {
			if x != "null" {
				t = x
			}
		}
	}
	if t == "array" && p.Items != nil {
		return typeOf(p.Items) + "[]"
	}
	return t
}

func code(ss []string) string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`" + s + "`"
	}
	return strings.Join(out, ", ")
}
