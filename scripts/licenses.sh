#!/bin/sh
# Prints THIRD_PARTY_LICENSES: for every module the tailkeeper binary links, on any release
# target, the module path, its version, the targets that link it, and the text of its
# licence files as the module cache holds them; and the Go standard library's licence. Run
# by `make deps` and checked by `make deps-check`, like scripts/deps.sh, so a dependency
# that changes, or a licence file that is not shipped, fails the gate until it is reviewed.
#
# It uses the go toolchain and the module cache only. A module with no licence file fails
# the run: shipping a binary that links code whose licence is not shipped is the thing this
# file exists to prevent.
set -eu
cd "$(dirname "$0")/.."

flags=""
for flag in ${GOFLAGS:-}; do
	if [ "$flag" != "-mod=readonly" ]; then flags="${flags:+$flags }$flag"; fi
done
GOFLAGS="${flags:+$flags }-mod=readonly"
export GOFLAGS
unset flags flag
LC_ALL=C
export LC_ALL

main=github.com/abm9111/tailkeeper/cmd/tailkeeper
targets="darwin/amd64 darwin/arm64 linux/amd64 linux/arm64 windows/amd64"

work="$(mktemp -d)" || exit 1
trap 'rm -f "$work"/*; rmdir "$work"' EXIT

# One list of "path version dir target" per release target. Each go list is captured on its
# own: a pipeline reports only its last command, so a failing go list would print a short,
# plausible file and exit 0. Test-only modules are not linked and do not appear.
: > "$work/all"
for target in $targets; do
	listed="$(GOOS="${target%/*}" GOARCH="${target#*/}" CGO_ENABLED=0 go list -deps \
		-f '{{if and (not .Standard) .Module (not .Module.Main)}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}' ./cmd/tailkeeper)"
	binary="$(GOOS="${target%/*}" GOARCH="${target#*/}" CGO_ENABLED=0 go list -deps -f '{{.ImportPath}}' ./cmd/tailkeeper)"
	if ! printf '%s\n' "$binary" | grep -qx "$main"; then
		echo "licenses.sh: go list for $target did not list $main" >&2
		exit 1
	fi
	if [ -z "$listed" ]; then
		echo "licenses.sh: no module outside tailkeeper for $target" >&2
		exit 1
	fi
	printf '%s\n' "$listed" | awk -v t="$target" 'NF { print $1, $2, $3, t }' >> "$work/all"
done

echo "THIRD-PARTY LICENSES"
echo
echo "tailkeeper links the modules below, and the Go standard library, into its binary. Each is"
echo "listed with the release targets that link it and the text of its licence files, copied from"
echo "the module cache. tailkeeper's own licence is in LICENSE."
echo
echo "Generated by \`make deps\` (scripts/licenses.sh) from \`go list -deps ./cmd/tailkeeper\` for"
echo "each release target. Do not edit by hand: \`make deps-check\`, which \`make verify\` runs,"
echo "fails when this file differs from what the code links."
echo
echo "Modules: $(awk '{ print $1, $2 }' "$work/all" | sort -u | wc -l | tr -d ' ')"

# One line per module and target (a module has many packages), then the modules in path order.
sort -u "$work/all" > "$work/unique"
mv "$work/unique" "$work/all"
awk '{ print $1, $2, $3 }' "$work/all" | sort -u > "$work/modules"
while read -r path version dir; do
	if [ -z "$dir" ] || [ ! -d "$dir" ]; then
		echo "licenses.sh: $path $version is not in the module cache ($dir)" >&2
		exit 1
	fi
	linked="$(awk -v p="$path" -v v="$version" '$1 == p && $2 == v { printf "%s%s", sep, $4; sep = ", " }' "$work/all")"
	echo
	echo "================================================================================"
	echo "$path $version"
	echo "linked on: $linked"
	n=0
	# Licence files at the top of the module: LICENSE, LICENCE, COPYING, NOTICE, PATENTS,
	# UNLICENSE, in any case and with any extension (LICENSE.md, LICENSE-APACHE). The glob
	# expands in byte order (LC_ALL=C above) and skips dot files, which no name here starts
	# with; a name with a space stays one word.
	for file in "$dir"/*; do
		[ -f "$file" ] || continue
		f="${file##*/}"
		case "$(printf '%s' "$f" | tr '[:upper:]' '[:lower:]')" in
		licen[cs]e | copying | notice | patents | unlicense) ;;
		licen[cs]e[._-]* | copying[._-]* | notice[._-]* | patents[._-]* | unlicense[._-]*) ;;
		*) continue ;;
		esac
		n=$((n + 1))
		echo "--------------------------------------------------------------------------------"
		echo "$f"
		echo "--------------------------------------------------------------------------------"
		cat "$dir/$f"
		# A file without a final newline would run into the next heading.
		if [ -n "$(tail -c 1 "$dir/$f")" ]; then echo; fi
	done
	if [ "$n" -eq 0 ]; then
		echo "licenses.sh: $path $version has no licence file at the top of $dir" >&2
		exit 1
	fi
done < "$work/modules"

goroot="$(go env GOROOT)"
goversion="$(go env GOVERSION)"
echo
echo "================================================================================"
echo "Go standard library $goversion"
echo "linked on: $(printf '%s' "$targets" | sed 's/ /, /g')"
for f in LICENSE PATENTS; do
	if [ ! -f "$goroot/$f" ]; then
		echo "licenses.sh: $goroot/$f does not exist" >&2
		exit 1
	fi
	echo "--------------------------------------------------------------------------------"
	echo "$f"
	echo "--------------------------------------------------------------------------------"
	cat "$goroot/$f"
	if [ -n "$(tail -c 1 "$goroot/$f")" ]; then echo; fi
done
