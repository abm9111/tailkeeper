package docsgen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/abm9111/tailkeeper/internal/registry"
)

// ScopeUse is one OAuth scope and the tools that declare it.
type ScopeUse struct {
	Scope string `json:"scope"`
	// Tools need the scope for their result.
	Tools []string `json:"tools"`
	// PartialTools read part of their result with the scope, and still work,
	// narrowed, without it (settings fields, key types).
	PartialTools []string `json:"partialTools,omitempty"`
	// OptionalTools run without the scope and use it for one feature, named by the
	// reason. Absent from the JSON when no tool uses the scope that way.
	OptionalTools []OptionalUse `json:"optionalTools,omitempty"`
	// AlphaOnly means only tools for alpha Tailscale features use the scope; MCP
	// lists those tools only with --enable-alpha.
	AlphaOnly bool `json:"alphaOnly,omitempty"`
	// Plans names the Tailscale plans of plan-gated tools that use the scope, as
	// "tool: plans".
	Plans []string `json:"plans,omitempty"`
}

// OptionalUse is one tool's optional use of a scope.
type OptionalUse struct {
	Tool   string `json:"tool"`
	Reason string `json:"reason"`
}

// Scopes returns every OAuth scope the tools in reg declare, sorted by name.
func Scopes(reg *registry.Registry) []ScopeUse { return scopeUses(reg.All()) }

// scopeUses is Scopes over a list of tools. Only read tools count, as in
// `tailkeeper doctor`: any other tier needs a credential this document does not
// describe. The registry refuses to hold such a tool with scopes today, so a test
// passes the list directly.
func scopeUses(tools []registry.Tool) []ScopeUse {
	by := map[string]*ScopeUse{}
	use := func(scope string) *ScopeUse {
		u, ok := by[scope]
		if !ok {
			// Tools starts empty, not nil: a scope only read in part encodes as
			// "tools": [], so a consumer can iterate it.
			u = &ScopeUse{Scope: scope, Tools: []string{}, AlphaOnly: true}
			by[scope] = u
		}
		return u
	}
	for _, t := range tools {
		m := t.Meta
		if m.Tier != registry.TierRead {
			continue
		}
		for _, o := range m.OptionalScopes {
			u := use(o.Scope)
			u.OptionalTools = append(u.OptionalTools, OptionalUse{Tool: m.Name, Reason: o.Reason})
			if m.Stage != registry.StageAlpha {
				u.AlphaOnly = false
			}
		}
		for _, s := range m.Scopes {
			u := use(s)
			if m.PartialScopes {
				u.PartialTools = append(u.PartialTools, m.Name)
			} else {
				u.Tools = append(u.Tools, m.Name)
			}
			if m.Stage != registry.StageAlpha {
				u.AlphaOnly = false
			}
			if m.PlanGate != "" {
				u.Plans = append(u.Plans, m.Name+": "+m.PlanGate)
			}
		}
	}
	out := make([]ScopeUse, 0, len(by))
	for _, u := range by {
		sort.Strings(u.Tools)
		sort.Strings(u.PartialTools)
		sort.Strings(u.Plans)
		sort.Slice(u.OptionalTools, func(i, j int) bool { return u.OptionalTools[i].Tool < u.OptionalTools[j].Tool })
		out = append(out, *u)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Scope < out[j].Scope })
	return out
}

// ScopesMarkdown renders docs/scopes.md: every OAuth scope and the tools that
// use it, so a read credential can be created with what it needs and no more.
func ScopesMarkdown(reg *registry.Registry) string {
	var b strings.Builder
	b.WriteString("# OAuth scopes\n\n")
	b.WriteString("Generated by `tailkeeper docs --scopes` from the tool registry. Do not edit by hand. `tailkeeper scopes` prints the same list.\n\n")
	b.WriteString("tailkeeper needs one OAuth client with read scopes only. Grant every scope below that is not marked alpha to run every tool; grant fewer to run fewer tools (each tool's scopes are in `docs/tools.md`). A tool in the third column reads part of its result with each of its scopes: it returns what the scopes you grant cover and says what it could not see, but fails with `scope_missing` if you grant none of them. A tool in the fourth column runs without the scope and uses it for one feature, named in brackets: granting it enables that feature, and the tool says what it left out when the scope is missing. `tailkeeper doctor` reports which scopes a configured client lacks (an optional one as information, not a failure), and fails if it holds a write scope.\n\n")
	b.WriteString("| Scope | Tools that need it | Tools that read part of their result with it | Tools that use it optionally | Notes |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, u := range Scopes(reg) {
		var notes []string
		if u.AlphaOnly {
			notes = append(notes, "alpha tools only (MCP lists them with `--enable-alpha`)")
		}
		if len(u.Plans) > 0 {
			notes = append(notes, "Tailscale plans: "+strings.Join(u.Plans, "; "))
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", u.Scope, code(u.Tools), code(u.PartialTools), optionalCell(u.OptionalTools), strings.Join(notes, "; "))
	}
	return b.String()
}

// optionalCell renders the tools that use a scope optionally, each with its reason.
func optionalCell(uses []OptionalUse) string {
	parts := make([]string, len(uses))
	for i, u := range uses {
		parts[i] = "`" + u.Tool + "` (" + cell(u.Reason) + ")"
	}
	return strings.Join(parts, ", ")
}
