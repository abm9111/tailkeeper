#!/bin/sh
# Prints docs/dependencies.md: every package outside the standard library that
# the tailkeeper binary links, per release target. Run by `make deps` and checked
# by `make deps-check`; a change means a dependency changed, and is reviewed.
set -eu
cd "$(dirname "$0")/.."

# The listing never changes go.mod or go.sum (spec §20), and sorts the same on every
# machine. -mod=readonly is appended to whatever GOFLAGS the caller has, so a GOFLAGS
# of -mod=mod cannot win (Go honours the last -mod) and the caller's other flags stay.
# Copies already there (make exports one) are dropped first, so there is exactly one.
# `make` does the same; this covers a direct run.
flags=""
for flag in ${GOFLAGS:-}; do
	if [ "$flag" != "-mod=readonly" ]; then flags="${flags:+$flags }$flag"; fi
done
GOFLAGS="${flags:+$flags }-mod=readonly"
export GOFLAGS
unset flags flag
LC_ALL=C
export LC_ALL

main=github.com/abm9111/tailkeeper/cmd/tailkeeper

echo "# Dependencies"
echo
echo "Generated by \`make deps\` (scripts/deps.sh) from \`go list -deps ./cmd/tailkeeper\`. Do not edit by hand: \`make deps-check\`, which \`make verify\` runs, fails when this file differs from what the code links."
echo
echo "Packages outside the standard library and outside tailkeeper itself, per release target. Test-only dependencies (such as \`gopkg.in/yaml.v3\`) are not linked and are not listed."
for target in darwin/amd64 darwin/arm64 linux/amd64 linux/arm64 windows/amd64; do
	echo
	echo "## $target"
	echo
	# Each stage is captured before the next reads it: a pipeline reports only its last
	# command, so a failing `go list` piped into sort and sed would print a short,
	# plausible list and exit 0.
	listed="$(GOOS="${target%/*}" GOARCH="${target#*/}" CGO_ENABLED=0 go list -deps \
		-f '{{if not .Standard}}{{.ImportPath}}{{end}}' ./cmd/tailkeeper)"
	# The listing must contain the binary's own main package, or it did not list the binary.
	if ! printf '%s\n' "$listed" | grep -qx "$main"; then
		echo "deps.sh: go list for $target did not list $main" >&2
		exit 1
	fi
	rows="$(printf '%s\n' "$listed" | awk 'NF && $0 !~ /^github\.com\/abm9111\/tailkeeper(\/|$)/' | sort)"
	if [ -z "$rows" ]; then
		echo "deps.sh: no dependency outside tailkeeper for $target" >&2
		exit 1
	fi
	# The backticks are Markdown code spans in the output, not a command.
	# shellcheck disable=SC2016
	printf '%s\n' "$rows" | sed 's/^/- `/; s/$/`/'
done
